DROP TABLE IF EXISTS dim_fecha, dim_municipio CASCADE;

-- ---------------------------------------------------------------------
-- 1. dim_fecha: no viene de ningún CSV, se GENERA con SQL.
--    Un día por fila, de 2025-01-01 a 2026-12-31 (cubre todas las fechas de los hechos).
--    fecha_key tiene formato AAAAMMDD, p. ej. 20260815.
-- ---------------------------------------------------------------------
CREATE TABLE dim_fecha (
    fecha_key           INTEGER PRIMARY KEY,
    fecha               DATE        NOT NULL UNIQUE,
    dia                 SMALLINT    NOT NULL,
    mes                 SMALLINT    NOT NULL,
    nombre_mes          VARCHAR(12) NOT NULL,
    trimestre           SMALLINT    NOT NULL,
    anio                SMALLINT    NOT NULL,
    dia_semana          SMALLINT    NOT NULL,       -- 1 = lunes ... 7 = domingo
    nombre_dia          VARCHAR(10) NOT NULL,
    es_fin_semana       BOOLEAN     NOT NULL,
    temporada_turistica VARCHAR(10) NOT NULL        -- alta / media / baja
);

INSERT INTO dim_fecha
SELECT
    TO_CHAR(d, 'YYYYMMDD')::INTEGER,
    d::DATE,
    EXTRACT(DAY FROM d),
    EXTRACT(MONTH FROM d),
    (ARRAY['enero','febrero','marzo','abril','mayo','junio','julio',
           'agosto','septiembre','octubre','noviembre','diciembre'])[EXTRACT(MONTH FROM d)],
    EXTRACT(QUARTER FROM d),
    EXTRACT(YEAR FROM d),
    EXTRACT(ISODOW FROM d),
    (ARRAY['lunes','martes','miércoles','jueves','viernes','sábado','domingo'])[EXTRACT(ISODOW FROM d)],
    EXTRACT(ISODOW FROM d) >= 6,
    CASE
        WHEN EXTRACT(MONTH FROM d) IN (7, 8)                         THEN 'alta'   -- verano
        WHEN EXTRACT(MONTH FROM d) = 12 AND EXTRACT(DAY FROM d) >= 20 THEN 'alta'   -- Navidad
        WHEN EXTRACT(MONTH FROM d) = 1  AND EXTRACT(DAY FROM d) <= 6  THEN 'alta'
        WHEN EXTRACT(MONTH FROM d) IN (4, 5, 6, 9, 10)               THEN 'media'
        ELSE 'baja'
    END
FROM generate_series(DATE '2025-01-01', DATE '2026-12-31', INTERVAL '1 day') AS d;

-- ---------------------------------------------------------------------
-- 2. dim_municipio: desde stg.municipios, convirtiendo los tipos.
--    - cod_ine 5001  -> '05001' (el código INE tiene 5 dígitos)
--    - longitud '-4,603775' -> -4.603775 (coma decimal a punto)
--    - fila 0 'DESCONOCIDO' para los registros cuyo municipio no se encuentre
-- ---------------------------------------------------------------------
CREATE TABLE dim_municipio (
    municipio_key  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cod_ine        CHAR(5)      NOT NULL,
    nombre         VARCHAR(100) NOT NULL,
    provincia      VARCHAR(50)  NOT NULL,
    poblacion      INTEGER,
    comarca        VARCHAR(100),
    pedanias       TEXT,                           -- Entidades Locales Menores (las usaremos al cruzar)
    latitud        NUMERIC(9,6),
    longitud       NUMERIC(9,6)
);

-- Miembro desconocido
INSERT INTO dim_municipio (municipio_key, cod_ine, nombre, provincia)
VALUES (0, '00000', 'DESCONOCIDO', 'DESCONOCIDA');

-- Municipios reales (municipio_key se genera solo: 1, 2, 3...)
INSERT INTO dim_municipio (cod_ine, nombre, provincia, poblacion, comarca, pedanias, latitud, longitud)
SELECT
    LPAD(cod_ine, 5, '0'),
    municipio,
    provincia,
    poblacion::INTEGER,
    comarca,
    entidades_locales_menores,
    REPLACE(latitud,  ',', '.')::NUMERIC(9,6),
    REPLACE(longitud, ',', '.')::NUMERIC(9,6)
FROM stg.municipios
ORDER BY cod_ine::INTEGER;

