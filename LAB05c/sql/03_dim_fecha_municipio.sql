SELECT 'dim_fecha' AS tabla, COUNT(*) AS filas, MIN(fecha)::TEXT AS desde, MAX(fecha)::TEXT AS hasta FROM dim_fecha
UNION ALL
SELECT 'dim_municipio', COUNT(*), MIN(cod_ine), MAX(cod_ine) FROM dim_municipio;
