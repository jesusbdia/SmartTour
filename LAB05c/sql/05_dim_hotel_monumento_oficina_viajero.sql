-- Cada dimensión se rellena desde su tabla stg con INSERT ... SELECT:
--   - stg.arreglar_tildes()  repara 'Ãvila'
--   - stg.a_numero()         convierte texto a número sin fallar ('10.0' -> 10)
--   - stg.buscar_municipio() averigua el municipio de cada hotel/monumento/oficina
--
-- Las dimensiones NO tienen clave foránea a municipio (modelo en estrella).
-- El municipio de cada una se guarda aparte, en tablas stg.mapa_*, para usarlo
-- al cargar los hechos: así cada hecho llevará su municipio_key.
-- =====================================================================

DROP TABLE IF EXISTS dim_hotel, dim_monumento, dim_oficina_turismo, dim_viajero CASCADE;
DROP TABLE IF EXISTS stg.mapa_hotel, stg.mapa_monumento, stg.mapa_oficina;

-- Convierte texto a número; si no es un número válido devuelve NULL
CREATE OR REPLACE FUNCTION stg.a_numero(texto TEXT)
RETURNS NUMERIC
LANGUAGE sql IMMUTABLE AS $$
    SELECT CASE
        WHEN TRIM(REPLACE(texto, ',', '.')) ~ '^-?[0-9]+(\.[0-9]+)?$'
        THEN TRIM(REPLACE(texto, ',', '.'))::NUMERIC
    END
$$;

-- =====================================================================
-- 1. dim_hotel  (2.378 alojamientos: hoteles y turismo rural)
-- =====================================================================
CREATE TABLE dim_hotel (
    hotel_key       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hotel_id        VARCHAR(20)  NOT NULL,   -- N.Registro (¡se repite entre hotel y rural!)
    establecimiento VARCHAR(50)  NOT NULL,   -- Alojamientos Hoteleros / Alojam. Turismo Rural
    nombre          VARCHAR(200) NOT NULL,
    tipo            VARCHAR(50),             -- Hotel, Hostal, Hotel Rural, Posada...
    categoria       VARCHAR(50),             -- texto original: '3 Estrellas', '2ª - 2 Estrellas'...
    estrellas       SMALLINT,                -- número extraído de la categoría
    plazas          INTEGER,
    direccion       VARCHAR(250),
    codigo_postal   VARCHAR(10),
    municipio       VARCHAR(100),            -- nombre tal como viene (descriptivo)
    localidad       VARCHAR(100),
    provincia       VARCHAR(50),
    telefono        VARCHAR(30),
    email           VARCHAR(150),
    web             VARCHAR(250),
    latitud         NUMERIC(9,6),
    longitud        NUMERIC(9,6),
    -- SCD tipo 2: vigencia de cada versión del hotel
    fecha_inicio    DATE    NOT NULL DEFAULT '2025-01-01',
    fecha_fin       DATE,
    es_actual       BOOLEAN NOT NULL DEFAULT TRUE,
    UNIQUE (establecimiento, hotel_id, fecha_inicio)
);

INSERT INTO dim_hotel (hotel_id, establecimiento, nombre, tipo, categoria, estrellas, plazas,
                       direccion, codigo_postal, municipio, localidad, provincia,
                       telefono, email, web, latitud, longitud)
SELECT
    n_registro,
    stg.arreglar_tildes(establecimiento),
    stg.arreglar_tildes(nombre),
    stg.arreglar_tildes(tipo),
    stg.arreglar_tildes(categoria),
    SUBSTRING(categoria FROM '(\d)\s*[Ee]strella')::SMALLINT,
    ROUND(stg.a_numero(plazas))::INTEGER,
    stg.arreglar_tildes(direccion),
    c_postal,
    stg.arreglar_tildes(municipio),
    stg.arreglar_tildes(localidad),
    stg.arreglar_tildes(provincia),
    telefono_1,
    email,
    web,
    CASE WHEN stg.a_numero(gps_latitud)  BETWEEN 40   AND 44   THEN stg.a_numero(gps_latitud)  END,
    CASE WHEN stg.a_numero(gps_longitud) BETWEEN -7.5 AND -1.5 THEN stg.a_numero(gps_longitud) END
FROM stg.hoteles
ORDER BY provincia, n_registro;

-- Municipio de cada hotel (se usará al cargar fact_reservas_hotel)
CREATE TABLE stg.mapa_hotel AS
SELECT h.hotel_key, h.hotel_id, h.establecimiento,
       stg.buscar_municipio(s.provincia, s.municipio, s.localidad) AS municipio_key
FROM dim_hotel h
JOIN stg.hoteles s
  ON s.n_registro = h.hotel_id
 AND stg.arreglar_tildes(s.establecimiento) = h.establecimiento;

-- =====================================================================
-- 2. dim_monumento  (1.374: hay 4 monumentos repetidos con dos tipos)
--    Ej.: Las Huelgas aparece como 'Monasterios' y como 'Reales Sitios'.
--    Dejamos una fila con el tipo concreto y marcamos es_real_sitio.
-- =====================================================================
CREATE TABLE dim_monumento (
    monumento_key     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    monumento_id      INTEGER      NOT NULL UNIQUE,   -- identificador de la Junta
    nombre            VARCHAR(250) NOT NULL,
    tipo              VARCHAR(100),
    es_real_sitio     BOOLEAN      NOT NULL,
    clasificacion     VARCHAR(100),
    tipo_construccion VARCHAR(100),
    periodo_historico VARCHAR(100),
    descripcion       TEXT,
    codigo_postal     CHAR(5),
    municipio         VARCHAR(100),
    localidad         VARCHAR(100),
    provincia         VARCHAR(50),
    latitud           NUMERIC(9,6),
    longitud          NUMERIC(9,6)
);

INSERT INTO dim_monumento (monumento_id, nombre, tipo, es_real_sitio, clasificacion, tipo_construccion,
                           periodo_historico, descripcion, codigo_postal, municipio, localidad,
                           provincia, latitud, longitud)
SELECT DISTINCT ON (identificador::INTEGER)            -- una fila por monumento
    identificador::INTEGER,
    stg.arreglar_tildes(nombre),
    stg.arreglar_tildes(tipo_monumento),
    EXISTS (SELECT 1 FROM stg.monumentos r
            WHERE r.identificador = m.identificador AND r.tipo_monumento = 'Reales Sitios'),
    stg.arreglar_tildes(clasificacion),
    stg.arreglar_tildes(tipo_construccion),
    stg.arreglar_tildes(periodo_historico),
    stg.arreglar_tildes(descripcion),
    LPAD(ROUND(stg.a_numero(codigo_postal))::TEXT, 5, '0'),   -- 5001.0 -> '05001'
    stg.arreglar_tildes(poblacion_municipio),
    stg.arreglar_tildes(poblacion_localidad),
    stg.arreglar_tildes(poblacion_provincia),
    CASE WHEN stg.a_numero(latitud)  BETWEEN 40   AND 44   THEN stg.a_numero(latitud)  END,
    CASE WHEN stg.a_numero(longitud) BETWEEN -7.5 AND -1.5 THEN stg.a_numero(longitud) END
FROM stg.monumentos m
ORDER BY identificador::INTEGER,
         (tipo_monumento = 'Reales Sitios');           -- FALSE primero: gana el tipo concreto

CREATE TABLE stg.mapa_monumento AS
SELECT d.monumento_key, d.monumento_id,
       stg.buscar_municipio(s.poblacion_provincia, s.poblacion_municipio, s.poblacion_localidad) AS municipio_key
FROM dim_monumento d
JOIN (SELECT DISTINCT ON (identificador) * FROM stg.monumentos) s
  ON s.identificador::INTEGER = d.monumento_id;

-- =====================================================================
-- 3. dim_oficina_turismo  (263)
-- =====================================================================
CREATE TABLE dim_oficina_turismo (
    oficina_key          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    oficina_id           INTEGER      NOT NULL UNIQUE,
    nombre               VARCHAR(250) NOT NULL,
    tipo_establecimiento VARCHAR(100),
    ambito               VARCHAR(50),             -- Municipal, Provincial, Regional...
    localidad            VARCHAR(100),
    provincia            VARCHAR(50)
);

INSERT INTO dim_oficina_turismo (oficina_id, nombre, tipo_establecimiento, ambito, localidad, provincia)
SELECT
    id_oficina::INTEGER,
    stg.arreglar_tildes(nombre),
    stg.arreglar_tildes(establecimiento),
    stg.arreglar_tildes(ambito),
    stg.arreglar_tildes(localidad),
    stg.arreglar_tildes(provincia)
FROM stg.oficinas
ORDER BY id_oficina::INTEGER;

CREATE TABLE stg.mapa_oficina AS
SELECT d.oficina_key, d.oficina_id,
       stg.buscar_municipio(s.provincia, s.localidad) AS municipio_key
FROM dim_oficina_turismo d
JOIN stg.oficinas s ON s.id_oficina::INTEGER = d.oficina_id;

-- =====================================================================
-- 4. dim_viajero  (10.000; viene de hechos/viajeros.csv)
-- =====================================================================
CREATE TABLE dim_viajero (
    viajero_key    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    viajero_id     INTEGER     NOT NULL UNIQUE,
    nombre         VARCHAR(100),
    apellido       VARCHAR(100),
    pais_origen    VARCHAR(100),
    edad           SMALLINT,
    tipo_viajero   VARCHAR(30),               -- Solo, Pareja, Familia, Grupo, Negocios
    fecha_registro DATE
);

INSERT INTO dim_viajero (viajero_id, nombre, apellido, pais_origen, edad, tipo_viajero, fecha_registro)
SELECT id_viajero::INTEGER, nombre, apellido, pais_origen, edad::SMALLINT, tipo_viajero, fecha_registro::DATE
FROM stg.viajeros
ORDER BY id_viajero::INTEGER;

-- =====================================================================
-- Comprobación: filas de cada dimensión y % con municipio identificado
-- =====================================================================
SELECT 'dim_hotel' AS dimension, COUNT(*) AS filas,
       (SELECT ROUND(100.0 * AVG((municipio_key > 0)::INT), 1) FROM stg.mapa_hotel) AS pct_con_municipio
FROM dim_hotel
UNION ALL
SELECT 'dim_monumento', COUNT(*),
       (SELECT ROUND(100.0 * AVG((municipio_key > 0)::INT), 1) FROM stg.mapa_monumento)
FROM dim_monumento
UNION ALL
SELECT 'dim_oficina_turismo', COUNT(*),
       (SELECT ROUND(100.0 * AVG((municipio_key > 0)::INT), 1) FROM stg.mapa_oficina)
FROM dim_oficina_turismo
UNION ALL
SELECT 'dim_viajero', COUNT(*), NULL
FROM dim_viajero;
